namespace Fluxer.Net;

/// <summary>
/// The content warning setting of a guild or channel.
/// </summary>
public enum GuildContentWarning
{
    /// <summary>
    /// Inherits the content warning setting.
    /// </summary>
    Inherit = 0,

    /// <summary>
    /// Shows a content warning.
    /// </summary>
    ContentWarning = 1
}
