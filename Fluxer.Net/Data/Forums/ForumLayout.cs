namespace Fluxer.Net;

/// <summary>
/// The layout a forum uses to show its posts.
/// </summary>
public enum ForumLayout
{
    /// <summary>
    /// The default layout.
    /// </summary>
    Default = 0,

    /// <summary>
    /// Posts are shown in a list view.
    /// </summary>
    List = 1,

    /// <summary>
    /// Posts are shown in a grid view.
    /// </summary>
    Grid = 2
}