namespace Fluxer.Net;

/// <summary>
/// The order in which a forum lists its posts.
/// </summary>
public enum ForumSortOrder
{
    /// <summary>
    /// Posts are sorted by their latest activity.
    /// </summary>
    LatestActivity = 0,

    /// <summary>
    /// Posts are sorted by when they were created.
    /// </summary>
    CreationDate = 1
}
